-- 使用说明：
-- 1. 本文件同时包含「建库建表」「旧库升级」「种子数据」「评分回算」四部分。
-- 2. 新库直接执行即可；旧库重复执行也不会重复插入种子数据。
-- 3. 所有番剧分数均来自 ratings 表中的真实用户评分，脚本不写入虚构评分人数。
-- 4. 文件末尾附带常用管理查询，默认全部注释，不会自动执行。
-- ============================================================

-- ------------------------------------------------------------
-- 第 1 部分：数据库与表结构
-- ------------------------------------------------------------

CREATE DATABASE IF NOT EXISTS acgn_screenroom
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE acgn_screenroom;

-- 1.1 用户表：登录账号、角色与加盐密码哈希
CREATE TABLE IF NOT EXISTS users (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '用户 ID',
  username VARCHAR(40) NOT NULL UNIQUE COMMENT '登录用户名',
  nickname VARCHAR(60) NOT NULL COMMENT '用户昵称，评论展示用',
  email VARCHAR(120) NOT NULL UNIQUE COMMENT '邮箱',
  password_hash VARCHAR(255) NOT NULL COMMENT '加盐 SHA-256 密码，格式：salt$hash',
  role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER' COMMENT '角色：普通用户 / 管理员',
  avatar_url VARCHAR(500) COMMENT '头像地址',
  bio VARCHAR(255) COMMENT '个人简介',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '注册时间'
) ENGINE=InnoDB COMMENT='用户表';

-- 1.2 作品表：番剧 / 电影基础信息
-- 注意：score 与 score_count 是 ratings 表的聚合缓存，由本脚本末尾统一回算。
CREATE TABLE IF NOT EXISTS anime (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '作品 ID',
  title VARCHAR(160) NOT NULL COMMENT '作品中文名',
  original_title VARCHAR(160) COMMENT '作品原名',
  summary TEXT COMMENT '剧情简介',
  cover_url VARCHAR(500) COMMENT '封面图片 URL，后台可修改',
  pv_url VARCHAR(500) COMMENT 'PV 视频地址，后台可修改',
  season VARCHAR(30) COMMENT '季度，如 2026 夏',
  media_type ENUM('ANIME','MOVIE') NOT NULL DEFAULT 'ANIME' COMMENT '作品类型：番剧 / 电影',
  status ENUM('AIRING','FINISHED','UPCOMING') NOT NULL DEFAULT 'UPCOMING' COMMENT '播出状态',
  score DECIMAL(3,1) NOT NULL DEFAULT 0 COMMENT '真实用户评分均分，由 ratings 回算',
  score_count INT NOT NULL DEFAULT 0 COMMENT '真实评分人数，由 ratings 回算',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '收录时间',
  INDEX idx_anime_season (season),
  INDEX idx_anime_score (score)
) ENGINE=InnoDB COMMENT='番剧与电影作品表';

-- 1.3 标签表与作品-标签关联表
CREATE TABLE IF NOT EXISTS genres (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '标签 ID',
  name VARCHAR(40) NOT NULL UNIQUE COMMENT '标签名称'
) ENGINE=InnoDB COMMENT='作品标签表';

CREATE TABLE IF NOT EXISTS anime_genres (
  anime_id BIGINT NOT NULL COMMENT '作品 ID',
  genre_id BIGINT NOT NULL COMMENT '标签 ID',
  PRIMARY KEY (anime_id, genre_id),
  FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE,
  FOREIGN KEY (genre_id) REFERENCES genres(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='作品与标签多对多关联表';

-- 1.4 评分表：真实评分的唯一数据源
-- 唯一约束保证「一个用户一部作品只有一条评分」。
CREATE TABLE IF NOT EXISTS ratings (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '评分 ID',
  user_id BIGINT NOT NULL COMMENT '评分用户 ID',
  anime_id BIGINT NOT NULL COMMENT '被评分作品 ID',
  score TINYINT NOT NULL COMMENT '用户评分，范围 1–10',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '评分 / 修改时间',
  UNIQUE KEY uk_user_anime_rating (user_id, anime_id),
  KEY idx_ratings_anime (anime_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE,
  CHECK (score BETWEEN 1 AND 10)
) ENGINE=InnoDB COMMENT='用户真实评分表';

-- 1.5 评论表：详情页评论与后台审核的数据源
CREATE TABLE IF NOT EXISTS comments (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '评论 ID',
  user_id BIGINT NOT NULL COMMENT '评论用户 ID',
  anime_id BIGINT NOT NULL COMMENT '所属作品 ID',
  content VARCHAR(1000) NOT NULL COMMENT '评论内容',
  likes INT NOT NULL DEFAULT 0 COMMENT '点赞数',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '发表时间',
  KEY idx_comments_anime_time (anime_id, created_at),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='作品评论表';

-- 1.6 追番片单表：想看 / 在看 / 看过，一个用户一部作品只有一条记录
CREATE TABLE IF NOT EXISTS watchlist (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '片单记录 ID',
  user_id BIGINT NOT NULL COMMENT '用户 ID',
  anime_id BIGINT NOT NULL COMMENT '作品 ID',
  status ENUM('WANT','WATCHING','WATCHED') NOT NULL DEFAULT 'WANT' COMMENT '观看状态',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '加入时间',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '状态更新时间',
  UNIQUE KEY uk_user_anime_watchlist (user_id, anime_id),
  KEY idx_watchlist_user_status (user_id, status),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (anime_id) REFERENCES anime(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='用户追番片单表';

-- 1.7 评论点赞表：记录用户与评论的一对一点赞关系，防止重复点赞
CREATE TABLE IF NOT EXISTS comment_likes (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '点赞 ID',
  user_id BIGINT NOT NULL COMMENT '点赞用户 ID',
  comment_id BIGINT NOT NULL COMMENT '被点赞评论 ID',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '点赞时间',
  UNIQUE KEY uk_user_comment_like (user_id, comment_id),
  KEY idx_comment_likes_comment (comment_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (comment_id) REFERENCES comments(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='评论点赞记录表';

-- 1.8 登录令牌表：服务端签发 / 校验 Bearer Token
CREATE TABLE IF NOT EXISTS auth_tokens (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '令牌 ID',
  user_id BIGINT NOT NULL COMMENT '所属用户 ID',
  token_hash VARCHAR(128) NOT NULL UNIQUE COMMENT '令牌 SHA-256 哈希，不存明文',
  expires_at TIMESTAMP NOT NULL COMMENT '过期时间，默认 7 天',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '签发时间',
  KEY idx_auth_tokens_user (user_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='登录令牌表';

