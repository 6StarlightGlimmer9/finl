-- 第 4 部分：真实评分回算
-- 每次执行脚本都会把 anime.score / score_count 校正为 ratings 的真实聚合值。
-- ------------------------------------------------------------

UPDATE anime a
SET score_count = (SELECT COUNT(*) FROM ratings r WHERE r.anime_id = a.id),
    score = ROUND(COALESCE((SELECT AVG(r.score) FROM ratings r WHERE r.anime_id = a.id), 0), 1);

